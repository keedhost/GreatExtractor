/// Повна назва + короткий опис використання (`usage_note`) кожного
/// підтримуваного формату, відсортовані за назвою — спільне джерело для
/// `--formats`/`-f` (CLI, `output::render_formats`) і довідкового
/// спливаючого вікна `?` у TUI, щоб обидва місця завжди показували
/// однакову інформацію.
pub fn all_formats() -> Vec<(&'static str, &'static str)> {
    let mut formats: Vec<(&'static str, &'static str)> =
        SIGNATURES.iter().map(|sig| (sig.name, usage_note(sig.name))).collect();
    // Регістронезалежне сортування — інакше "glTF-Binary" (мала літера)
    // опинився б в самому кінці списку, після "ZSTD".
    formats.sort_unstable_by_key(|(name, _)| name.to_lowercase());
    formats
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn all_formats_covers_every_signature_exactly_once() {
        let formats = all_formats();
        assert_eq!(formats.len(), SIGNATURES.len());

        let mut names: Vec<&str> = formats.iter().map(|(name, _)| *name).collect();
        names.sort_unstable();
        names.dedup();
        assert_eq!(names.len(), SIGNATURES.len(), "у SIGNATURES є дублікати назв");
    }

    #[test]
    fn all_formats_is_sorted_case_insensitively() {
        let formats = all_formats();
        for pair in formats.windows(2) {
            let (a, _) = pair[0];
            let (b, _) = pair[1];
            assert!(a.to_lowercase() <= b.to_lowercase(), "{a} має йти після {b}");
        }
    }

    #[test]
    fn all_formats_have_non_empty_descriptions() {
        for (name, note) in all_formats() {
            assert!(!note.is_empty(), "{name} має порожній опис");
        }
    }
}
