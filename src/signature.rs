use crate::validators;

/// Структурний валідатор: розбирає внутрішню структуру формату, щоб отримати
/// точну межу файлу. Повертає `(offset_end, confidence)` або `None`,
/// якщо структуру розібрати не вдалося (тоді застосовується `end_marker`
/// або евристика).
pub type Validator = fn(&[u8], usize) -> Option<(usize, u8)>;

/// Витягує ім'я файлу/запису, вбудоване у структуру формату (напр. запис
/// каталогу TAR/CPIO/ar/WAD/PAK), якщо воно є. `None`, якщо формат не
/// зберігає імен (більшість "одиночних" форматів) або структуру не вдалося
/// розібрати.
pub type NameExtractor = fn(&[u8], usize) -> Option<String>;

/// Опис однієї сигнатури формату файлу.
pub struct Signature {
    /// Назва формату (напр. "PNG", "ZIP").
    pub name: &'static str,
    /// Людський опис для виводу.
    pub description: &'static str,
    /// Байти магічного числа.
    pub magic: &'static [u8],
    /// Зсув магічних байтів відносно початку самого файлу
    /// (0 для більшості форматів, >0 для форматів на кшталт TAR,
    /// де магічні байти лежать усередині заголовка).
    pub relative_offset: usize,
    /// Структурний валідатор точних меж — має пріоритет над `end_marker`.
    pub validator: Option<Validator>,
    /// Маркер кінця файлу, якщо формат його має (шукається після magic).
    /// Використовується, лише якщо `validator` відсутній або не спрацював.
    pub end_marker: Option<&'static [u8]>,
    /// Розширення файлу для іменування витягнутих фрагментів.
    pub extension: &'static str,
    /// Витягує вбудоване ім'я файлу/запису, якщо формат його зберігає
    /// (TAR/CPIO/ar/WAD/PAK тощо). `None` для форматів без такої концепції.
    pub name_extractor: Option<NameExtractor>,
}

/// Розширення файлу за назвою формату — для іменування витягнутих фрагментів.
pub fn extension_for(format_name: &str) -> &'static str {
    SIGNATURES
        .iter()
        .find(|s| s.name == format_name)
        .map(|s| s.extension)
        .unwrap_or("bin")
}

